// 消息整理的判定准则（唯一来源）。
// 同一份文本用在三处，改这里就够了，不要再往别处抄一份：
//   1) 内置 AI 规则「滤掉无用信息」的规则内容（规则页可见，只有开关能改）
//   2) 实时判定（AiClient.judgeAndBrief）的 system 提示
//   3) 批量整理（AiClient.judgeBatch）的 system 提示
// 范围（收哪些应用、哪些群）不在这里管，只管「什么留、什么去」。
package com.lvjian.app.rules

object TriageRules {

    /** 内置规则名；改名字会让旧安装多出一条重复规则，别动 */
    const val NAME = "滤掉无用信息"

    /** 判断方法（短版），塞进 system 提示当兜底；完整清单在 PATTERN 里 */
    val FALLBACK: String =
        "判定原则：作业、上课、考试、测验、截止、地点变更、@我、@所有人、要求回复确认、招聘机会一律保留；" +
            "系统提示、验证码、营销广告、纯闲聊、只@了别人的对话丢弃；拿不准保留。"

    /** 丢弃清单 + 保留清单。用户能在规则页看到全文。 */
    val PATTERN: String = """
        【丢弃】只滤掉明确无用的消息：

        1. 系统状态与提示：充电、USB、电量、互传、调试、网络切换。
        2. 营销广告、促销、优惠券、拉新、拼团、开课推销。
        3. 验证码、登录提醒、账号安全播报、异地登录。
        4. 纯寒暄、没有正文的表情包、与学习工作无关的闲聊刷屏。
        5. 群里只 @ 了别人，既没有「有人@我」也没有 @所有人 的对话。
        6. 已有结果、不需要再动手的事：已经回复且对方不再追问、已经成交或收款、已经确认收到。
        7. 家教群、家教单、上门辅导、教员招聘（私下单独找我做家教的除外）。

        【必须保留，不得过滤】：

        1. 有人@我、@所有人、@所有成员。
        2. 作业、课件、教材、作业提交方式与时间、上课地点、调课。
        3. 考试、测验、考核、成绩、报名、问卷、提交、签到、到场、截止时间。
        4. 会议、活动、讲座、面试的时间、地点与变更。
        5. 招聘、兼职、实习、内推机会。
        6. 要我确认、回复、付款、填写的事项。
        7. 约饭、聚会这类要约——是事情，不是闲聊。
        8. 图片、文件、语音只有占位文字、看不出内容的，保留。

        【判断方法】按整条消息和前后文判断，不按单个词机械分类；
        作业和测验是两件事，各自的时间和规则都要留；拿不准一律保留。
    """.trimIndent()
}